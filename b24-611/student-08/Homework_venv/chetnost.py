num = int(input("Введите целое число: "))

if num == 0:
    print("Число 0 (ни чётное, ни нечётное)")
elif num < 0:
    if num % 2 == 0:
        print(f"{num} — отрицательное чётное число")
    else:
        print(f"{num} — отрицательное нечётное число")
else:
    if num % 2 == 0:
        print(f"{num} — положительное чётное число")
    else:
        print(f"{num} — положительное нечётное число")
